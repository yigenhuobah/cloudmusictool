def java_constant(key: str) -> str:
    """与 AnchorContractTest.constantName 保持同一规则（TB 约定）。"""
    return re.sub(r"[^0-9A-Za-z]+", "_", key).upper()


def load_anchors() -> dict:
    with ANCHORS_PATH.open(encoding="utf-8") as handle:
        return json.load(handle)


def write_text(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def validate_document(document: dict) -> None:
    if document.get("schemaVersion") != 1:
        raise SystemExit("unsupported schemaVersion: %r" % document.get("schemaVersion"))
    anchors = document.get("anchors")
    if not isinstance(anchors, dict) or not anchors:
        raise SystemExit("anchors 段缺失或为空")
    mount_ids = set()
    for key, entry in anchors.items():
        if not entry.get("note"):
            raise SystemExit("anchor 缺少 note: " + key)
        if "critical" not in entry:
            raise SystemExit("anchor 缺少 critical: " + key)
        if not entry.get("feature"):
            raise SystemExit("anchor 缺少 feature: " + key)
        if entry.get("key"):
            raise SystemExit("anchor 使用旧 schema 的 key 字段: " + key)
        if entry.get("feature") and entry.get("logicalName"):
            mount_ids.add("%s/%s" % (entry["feature"], entry["logicalName"]))

    profiles = document.get("profiles") or []
    by_name = {}
    for profile in profiles:
        name = profile.get("versionName")
        if not name:
            raise SystemExit("profile 缺少 versionName")
        if name in by_name:
            raise SystemExit("profile versionName 重复: " + name)
        by_name[name] = profile

    for profile in profiles:
        name = profile.get("versionName")
        for key in profile.get("mounts") or []:
            if key not in anchors:
                raise SystemExit("profile %s 引用了不存在的 key: %s" % (name, key))
        remove = profile.get("remove")
        if remove is None:
            continue
        if not isinstance(remove, list):
            raise SystemExit("profile %s 的 remove 必须是字符串数组" % name)
        for mount_id in remove:
            if not isinstance(mount_id, str) or "/" not in mount_id:
                raise SystemExit("profile %s 的 remove 元素必须是 feature/logicalName: %r"
                                 % (name, mount_id))
            if mount_id not in mount_ids:
                raise SystemExit("profile %s remove 了不存在的 mount id: %s"
                                 % (name, mount_id))

    # 与 AnchorTable.buildMounts / check-mounts.sh 同步：remove 必须在展开后的
    # base 链里真实存在（先 remove 再合并 mounts），否则 build 期必须报错。
    for profile in profiles:
        chain, seen, cur = [], set(), profile.get("versionName")
        while cur:
            if cur in seen:
                raise SystemExit("profile base cycle at: " + str(cur))
            seen.add(cur)
            item = by_name.get(cur)
            if item is None:
                raise SystemExit("profile base not found: " + str(cur))
            chain.append(item)
            cur = item.get("base")
        merged = set()
        for item in reversed(chain):
            item_name = item.get("versionName")
            for mount_id in item.get("remove") or []:
                if mount_id not in merged:
                    raise SystemExit("profile %s 的 remove 在 base 链中不存在: %s"
                                     % (item_name, mount_id))
                merged.discard(mount_id)
            for key in item.get("mounts") or []:
                entry = anchors[key]
                feature = str(entry.get("feature", ""))
                logical = entry.get("logicalName")
                if not logical:
                    prefix = feature + "/"
                    logical = (str(key)[len(prefix):]
                               if str(key).startswith(prefix) else str(key))
                merged.add(feature + "/" + str(logical))


def dexkit_sections(document: dict) -> list:
    """把 anchors 条目的内联 dexkit 数组映射回常量名/说明。"""
    known = {}
    for name, note, anchors in DEXKIT_SECTIONS:
        marker = tuple(anchors)
        if marker in known:
            raise SystemExit("DexKitAnchors 常量数组重复：%s / %s"
                             % (known[marker][0], name))
        known[marker] = (name, note)
    used = set()
    for key, entry in document.get("anchors", {}).items():
        if "dexkit" not in entry:
            continue
        marker = tuple(entry["dexkit"])
        if not marker:
            raise SystemExit("空 dexkit: " + key)
        if marker not in known:
            raise SystemExit("dexkit 数组不对应任何常量: %s -> %s"
                             % (key, list(marker)))
        used.add(known[marker][0])
    for name, _note, anchors in DEXKIT_SECTIONS:
        if name not in used:
            raise SystemExit("DexKitAnchors 常量未被任何锚点引用: " + name)
    return [(name, note, list(anchors)) for name, note, anchors in DEXKIT_SECTIONS
            if name in used]


def render_anchor_keys(document: dict) -> str:
    keys = list(document["anchors"].keys())
    names = {}
    for key in keys:
        name = java_constant(key)
        if name in names:
            raise SystemExit("AnchorKeys 常量名冲突：%s / %s -> %s"
                             % (names[name], key, name))
        names[name] = key
    lines = [
        HEADER,
        "package com.cloudmusictool.app.anchor;",
        "",
        "/**",
        " * anchors.json 中全部锚点键的编译期常量。",
        " *",
        " * <p>key 即 anchors 段的 map key；版本变体形如 {@code mountId@版本名}。",
        " * 生成规则：key 的非字母数字字符折叠为下划线并转大写（与 TB 模块一致）。",
        " * AnchorContractTest 校验常量与 anchors.json 双向一致；新增/删除锚点后",
        " * 运行 {@code python3 tools/gen_anchors.py} 重新生成，不要手改本文件。",
        " */",
        "public final class AnchorKeys {",
        "",
        "    private AnchorKeys() {",
        "    }",
        "",
    ]
    for key in keys:
        lines.append('    public static final String %s = "%s";'
                     % (java_constant(key), key))
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_dexkit_anchors(document: dict) -> str:
    lines = [
        HEADER,
        "package com.cloudmusictool.app.dexkit;",
        "",
        "/**",
        " * 逻辑名 -> 真实 dex 字符串字面量表（与 anchors.json 的 dexkit 数组对应）。",
        " *",
        " * <p>DexKit 的 ClassMatcher.addUsingString 匹配的是「该类方法里实际使用的",
        " * dex 字符串字面量」，不是类名/方法名。所有值均用 dexsql 的 method_strings",
        " * 在目标 APK 上验证过，并确认只命中目标类。",
        " *",
        " * <p>维护方式：改 anchors.json 条目的 dexkit 数组，再运行",
        " * {@code python3 tools/gen_anchors.py}；AnchorContractTest 会拦截漂移。",
        " */",
        "public final class DexKitAnchors {",
        "",
        "    private DexKitAnchors() {",
        "    }",
    ]
    for name, note, anchors in dexkit_sections(document):
        lines.append("")
        if note:
            lines.append("    /** %s */" % note)
        lines.append("    public static final String[] %s = {" % name)
        for index, anchor in enumerate(anchors):
            comma = "," if index + 1 < len(anchors) else ""
            lines.append("            %s%s" % (json.dumps(anchor, ensure_ascii=False), comma))
        lines.append("    };")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="只校验 Java 派生文件是否与 anchors.json 一致")
    args = parser.parse_args()

    document = load_anchors()
    validate_document(document)
    expected = {
        ANCHOR_KEYS_PATH: render_anchor_keys(document),
        DEXKIT_ANCHORS_PATH: render_dexkit_anchors(document),
    }
    drifted = []
    for path, text in expected.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            drifted.append(path)
            if not args.check:
                write_text(path, text)
    if args.check:
        if drifted:
            for path in drifted:
                print("out of date: %s" % path, file=sys.stderr)
            print("运行 python3 tools/gen_anchors.py 重新生成。", file=sys.stderr)
            return 1
        print("anchors.json 与 Java 派生文件一致。")
        return 0
    for path in drifted:
        print("generated: %s" % path)
    if not drifted:
        print("Java 派生文件已是最新。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
