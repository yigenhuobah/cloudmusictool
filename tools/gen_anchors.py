#!/usr/bin/env python3
"""anchors.json 工具：从锚点表生成 Java 派生文件，并校验统一 schema 的引用完整性。

数据流（单向，anchors.json 是唯一来源）：
    anchors.json --(gen)--> AnchorKeys.java / DexKitAnchors.java
    anchors.json --(ProfileExportTest / AnchorContractTest)--> profileXXXX.json / 契约断言

用法：
    python3 tools/gen_anchors.py            # 重新生成两个 Java 派生文件
    python3 tools/gen_anchors.py --check    # 只校验派生文件是否与 anchors.json 同步

anchors.json 的公共 core 与 TB/QB/QM 一致；CMT 额外有 app/profiles（多宿主版本分发）：
    { schemaVersion, generatedBy, app, appVersion, versionCode,
      anchors, classes, profiles }
anchors 段以锚点 key 为键（不再有 entry.key）；entries 里的 dexkit 是内联的
dex 字符串字面量数组，本脚本把它映射回 DexKitAnchors.java 的常量名。
"""

